# /// script
# requires-python = ">=3.12"
# dependencies = ["keyring>=25"]
# ///
"""Export the host's gcx configuration and keyring tokens to grafana.env for the MCP container.

Runs on the workstation: reads `gcx config view --raw -o json`, resolves `keychain:` token
references through the OS keyring and writes GRAFANA_* variables. Tokens are never printed.
"""

from __future__ import annotations

import argparse
import contextlib
import json
import os
import re
import subprocess
import sys
import tempfile
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

BEGIN = "# >>> grafana-mcp (generated by scripts/gcx_to_env.py) >>>"
END = "# <<< grafana-mcp <<<"
_TOKEN_PREFIXES = ("glsa_", "glc_")


@dataclass(frozen=True)
class ExportedEnv:
    name: str
    url: str
    token: str
    org_id: int = 1


def env_prefix(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def parse_keychain_ref(ref: str) -> tuple[str, str]:
    """`keychain:gcx:v2:A:B` -> (`gcx`, `v2:A:B`)."""
    parts = ref.split(":", 2)
    if len(parts) != 3 or parts[0] != "keychain" or not parts[1] or not parts[2]:
        raise ValueError("not a keychain reference")
    return parts[1], parts[2]


def _is_hint(line: str) -> bool:
    try:
        obj = json.loads(line)
    except ValueError:
        return False
    return isinstance(obj, dict) and obj.get("class") == "hint"


def load_gcx_config(gcx: str = "gcx") -> dict[str, Any]:
    proc = subprocess.run(
        [gcx, "config", "view", "--raw", "-o", "json"],
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise SystemExit(f"`{gcx} config view` failed with exit code {proc.returncode}")
    lines = [ln for ln in proc.stdout.splitlines() if ln.strip() and not _is_hint(ln)]
    try:
        cfg = json.loads("\n".join(lines))
    except ValueError:
        raise SystemExit(f"`{gcx} config view` did not return valid JSON") from None
    if not isinstance(cfg, dict):
        raise SystemExit(f"`{gcx} config view` returned unexpected JSON")
    return cfg


def unwrap_token(value: str) -> str:
    """The keyring stores the bare token (verified), so this is the identity."""
    return value


def collect(
    config: dict[str, Any],
    only: set[str] | None,
    get_password: Callable[[str, str], str | None],
) -> tuple[list[ExportedEnv], list[str]]:
    warnings: list[str] = []
    envs: list[ExportedEnv] = []
    stacks = config.get("stacks") or {}
    contexts = config.get("contexts") or {}
    if only:
        for unknown in sorted(only - set(contexts)):
            warnings.append(f"context '{unknown}' not found in gcx config")
    for name, ctx in contexts.items():
        if only is not None and name not in only:
            continue
        stack_name = (ctx or {}).get("stack")
        if name == "default" and not stack_name:
            continue  # gcx's placeholder context: nothing to export, nothing to warn about
        if not stack_name or stack_name not in stacks:
            warnings.append(f"context '{name}' skipped: no stack configured")
            continue
        graf = (stacks[stack_name] or {}).get("grafana") or {}
        if graf.get("auth-method") != "token":
            warnings.append(
                f"context '{name}' skipped: auth-method is "
                f"'{graf.get('auth-method')}', only token auth is supported"
            )
            continue
        server = graf.get("server")
        token = graf.get("token")
        if not server or not token:
            warnings.append(f"context '{name}' skipped: missing server or token")
            continue
        if token.startswith("keychain:"):
            try:
                service, user = parse_keychain_ref(token)
            except ValueError:
                raise SystemExit(f"context '{name}': malformed keychain reference") from None
            try:
                secret = get_password(service, user)
            except Exception:
                # Fixed message on purpose: the exception text could echo the reference.
                raise SystemExit(
                    f"context '{name}': keyring unavailable or locked "
                    "(unlock your keyring and retry)"
                ) from None
            if not secret:
                raise SystemExit(f"context '{name}': keyring entry not found (is it unlocked?)")
            token = unwrap_token(secret)
        envs.append(
            ExportedEnv(
                name=name,
                url=str(server).strip().rstrip("/"),
                token=token,
                org_id=int(graf.get("org-id") or 1),
            )
        )
    return envs, warnings


def render_block(envs: list[ExportedEnv]) -> str:
    lines = [BEGIN, f"GRAFANA_ENVIRONMENTS={','.join(e.name for e in envs)}"]
    for e in envs:
        p = env_prefix(e.name)
        lines += [
            f"GRAFANA_{p}_URL={e.url}",
            f"GRAFANA_{p}_TOKEN={e.token}",
            f"GRAFANA_{p}_ORG_ID={e.org_id}",
        ]
    lines.append(END)
    return "\n".join(lines) + "\n"


def merge_env(existing: str | None, block: str) -> str:
    """Replace the marked block (the first one; later duplicates are dropped) or append it.

    Raises SystemExit if a BEGIN marker has no matching END, so no user lines are lost.
    """
    if not existing:
        return block
    out: list[str] = []
    replaced = False
    skipping = False
    for ln in existing.splitlines():
        if skipping:
            if ln.strip() == END:
                skipping = False
            continue
        if ln.strip() == BEGIN:
            skipping = True
            if not replaced:
                out.append(block.rstrip("\n"))
                replaced = True
            continue
        out.append(ln)
    if skipping:
        raise SystemExit(
            "existing file has a grafana-mcp BEGIN marker without a matching END marker; "
            "fix or remove it manually (nothing was written)"
        )
    if not replaced:
        out.append(block.rstrip("\n"))
    return "\n".join(out) + "\n"


def _keyring_get_password(service: str, user: str) -> str | None:
    import keyring

    return keyring.get_password(service, user)


def _atomic_write(path: Path, content: str) -> None:
    """Write via a 0600 temp file in the same directory, then rename over the target."""
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(content)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--contexts", help="comma-separated gcx contexts to export (default: all)")
    ap.add_argument(
        "--output", default="grafana.env", help="output path (default: grafana.env)"
    )
    ap.add_argument("--force", action="store_true", help="update an existing output file")
    args = ap.parse_args(argv)

    out = Path(args.output)
    if out.exists() and not args.force:
        raise SystemExit(f"{out} exists; use --force to update its grafana-mcp block")
    only = {c.strip() for c in args.contexts.split(",") if c.strip()} if args.contexts else None

    envs, warnings = collect(load_gcx_config(), only, _keyring_get_password)
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    for e in envs:
        if not e.token.startswith(_TOKEN_PREFIXES):
            print(
                f"warning: token for '{e.name}' does not start with glsa_/glc_ "
                "(unexpected keyring value shape)",
                file=sys.stderr,
            )
    if not envs:
        raise SystemExit("no environments to export")

    existing = out.read_text() if out.exists() else None
    content = merge_env(existing, render_block(envs))
    _atomic_write(out, content)
    print(f"Wrote {len(envs)} environments to {out}: {', '.join(e.name for e in envs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
